#!/usr/bin/env python3
import os
import sys
import subprocess
import shutil

# --- Configuration ---
PROJECT_NAME = "gravitas"
KERNEL_FILE = f"bin/{PROJECT_NAME}.elf"
COMPILER = "clang++"
LINKER = "ld.lld"

# Flags
CFLAGS = [
    "-target x86_64-unknown-none-elf",
    "-ffreestanding",
    "-fno-builtin",
    "-fno-pie", "-fno-pic",
    "-mcmodel=kernel",
    "-fno-stack-protector",
    "-fno-rtti",
    "-fno-exceptions",
    "-fstack-protector-strong",
    "-mno-red-zone",
    "-mno-mmx", "-mno-sse", "-mno-sse2",
    "-Wall", "-Wextra",
    "-Isrc",
    "-std=c++20",
    "-g",
]

# Userland: libc headers ONLY (no kernel include paths) so the boundary
# stays clean — kernel code can't include libc, userland can't see kernel.
#
# SSE is enabled here (unlike the kernel): doubles are passed in xmm, and the
# scheduler saves/restores the XMM state per task. The kernel stays integer
# only so an interrupt can never clobber a task's xmm registers.
USER_CFLAGS = [
    "-target x86_64-unknown-none-elf",
    "-ffreestanding",
    "-fstack-protector-strong",
    "-fno-pie", "-fno-pic",
    "-mno-red-zone",
    "-Wall", "-Wextra",
    "-Isrc/libc/include",
    "-g",
    # One function/data item per section, so the link can drop everything a
    # program does not use (Gravity and libc pieces it never calls).
    "-ffunction-sections", "-fdata-sections",
]

# libc C sources compile as C11.
LIBC_CFLAGS = USER_CFLAGS + ["-std=c11", "-fno-builtin"]

# libc C++ sources (crt0, cxx runtime)
LIBC_CXXFLAGS = USER_CFLAGS + ["-std=c++20", "-fno-rtti", "-fno-exceptions", "-fno-builtin"]

LDFLAGS = [
    "-nostdlib",
    "-static",
    "-z", "max-page-size=0x1000",
    "-T", "src/arch/x86_64/linker.ld",
]

# --- Helper Functions ---

def run_command(cmd, cwd=None):
    try:
        subprocess.check_call(cmd, shell=True, cwd=cwd)
    except subprocess.CalledProcessError:
        print(f"Error running command: {cmd}")
        sys.exit(1)

def ensure_limine():
    if os.path.exists("limine/limine"):
        return 
    print("--- [Setup] Limine not found. Installing... ---")
    if not os.path.exists("limine"):
        run_command("git clone https://github.com/limine-bootloader/limine.git --branch=v8.x-binary --depth=1")
    run_command("make", cwd="limine")
    shutil.copy("limine/limine.h", "src/limine.h")

def find_sources(directory, extensions):
    sources = []
    for root, dirs, files in os.walk(directory):
        for file in files:
            if any(file.endswith(ext) for ext in extensions):
                sources.append(os.path.join(root, file))
    return sources

# --- Main ---

def main():
    ensure_limine()
    
    cpp_sources = find_sources("src", [".cpp"])
    asm_sources = find_sources("src", [".S"])
    cpp_sources = [f for f in cpp_sources if "aarch64" not in f]
    asm_sources = [f for f in asm_sources if "aarch64" not in f]

    # Userland programs: compiled into separate ELFs, NOT linked into the kernel
    user_sources = [f for f in cpp_sources if f.startswith("src/user/")]
    cpp_sources = [f for f in cpp_sources if not f.startswith("src/user/")]
    # The libc builds separately (its own rules); never part of the kernel
    cpp_sources = [f for f in cpp_sources if not f.startswith("src/libc/")]

    print(f"Configuring for {len(cpp_sources)} C++ files...")

    with open("build.ninja", "w") as ninja:
        ninja.write(f"# Auto-generated by configure.py\n\n")
        
        # --- RULES ---
        # -MMD depfiles: without these, header edits don't recompile their
        # dependents (a stale-object link error waiting to happen).
        ninja.write(f"rule cxx\n")
        ninja.write(f"  command = {COMPILER} {' '.join(CFLAGS)} -MMD -MF $out.d -c $in -o $out\n")
        ninja.write(f"  depfile = $out.d\n")
        ninja.write(f"  deps = gcc\n")
        ninja.write(f"  description = CXX $in\n\n")

        ninja.write(f"rule asm\n")
        ninja.write(f"  command = {COMPILER} {' '.join(CFLAGS)} -MMD -MF $out.d -c $in -o $out\n")
        ninja.write(f"  depfile = $out.d\n")
        ninja.write(f"  deps = gcc\n")
        ninja.write(f"  description = ASM $in\n\n")

        ninja.write(f"rule link\n")
        ninja.write(f"  command = {LINKER} {' '.join(LDFLAGS)} $in -o $out\n")
        ninja.write(f"  description = LINK $out\n\n")

        # Userland: one freestanding ELF per source, linked at 0x400000
        # (must match USER_CODE_ADDR in the kernel)
        user_link_flags = " ".join([
            "-nostdlib", "-static", "-Wl,--build-id=none",
            "-Wl,-Ttext=$base", "-Wl,-z,max-page-size=0x1000",
            "-Wl,-e,_start", "-Wl,--gc-sections",
        ])
        ninja.write(f"rule userelf\n")
        ninja.write(f"  command = {COMPILER} {' '.join(USER_CFLAGS + ['-std=c++20', '-fno-rtti', '-fno-exceptions'])} {user_link_flags} $in -o $out\n")
        ninja.write(f"  description = USER $out\n\n")

        # libc objects: compiled ONCE, linked into every userland program
        ninja.write(f"rule libc_c\n")
        ninja.write(f"  command = clang {' '.join(LIBC_CFLAGS)} -MMD -MF $out.d -c $in -o $out\n")
        ninja.write(f"  depfile = $out.d\n")
        ninja.write(f"  deps = gcc\n")
        ninja.write(f"  description = LIBC-C $out\n\n")
        ninja.write(f"rule libc_cxx\n")
        ninja.write(f"  command = {COMPILER} {' '.join(LIBC_CXXFLAGS)} -MMD -MF $out.d -c $in -o $out\n")
        ninja.write(f"  depfile = $out.d\n")
        ninja.write(f"  deps = gcc\n")
        ninja.write(f"  description = LIBC-CXX $out\n\n")

        ninja.write(f"rule iso\n")
        ninja.write(f"  command = ./build_iso.sh\n")
        ninja.write(f"  description = ISO gravitas.iso\n\n")
        
        # --- libc objects (once, reused by every program) ---
        libc_dir = "src/libc"
        libc_objects = []
        for root, dirs, files in os.walk(libc_dir):
            for file in files:
                src_path = os.path.join(root, file)
                if file.endswith(".c"):
                    obj = "obj/libc/" + src_path.replace("/", "_") + ".o"
                    ninja.write(f"build {obj}: libc_c {src_path}\n")
                    libc_objects.append(obj)
                elif file.endswith(".cpp") and "crt0" not in file:
                    # crt0 must come FIRST in the link (defines _start);
                    # handled separately below.
                    obj = "obj/libc/" + src_path.replace("/", "_") + ".o"
                    ninja.write(f"build {obj}: libc_cxx {src_path}\n")
                    libc_objects.append(obj)

        crt0_obj = "obj/libc/src_libc_cxx_crt0.cpp.o"
        ninja.write(f"build {crt0_obj}: libc_cxx {libc_dir}/cxx/crt0.cpp\n")

        # --- THE FIX IS HERE ---
        # Note the spaces inside the quotes for 'command', 'description', and 'pool'
        ninja.write(f"rule run\n")
        # KVM when available (10-50x TCG), else TCG fallback.
        # VNC instead of a local SDL/GTK window: QEMU's local display
        # scaling + pointer grab corrupts the presented framebuffer (the
        # guest's own framebuffer is correct — verified by screendump). VNC
        # carries dirty rectangles straight to the viewer.
        #   connect a viewer to localhost:5900 (e.g. `vncviewer localhost:0`)
        # Serial stays in this terminal.
        accel = "-enable-kvm" if os.path.exists("/dev/kvm") else ""
        ninja.write(f"  command = qemu-system-x86_64 -cdrom gravitas.iso -m 512M -serial stdio -display sdl {accel}\n")
        ninja.write(f"  description = RUN gravitas.iso\n")
        ninja.write(f"  pool = console\n\n")  # This allows interactive output!

        ninja.write(f"rule smoke\n")
        ninja.write(f"  command = ./smoke_test.sh\n")
        ninja.write(f"  description = SMOKE TEST\n")
        ninja.write(f"  pool = console\n\n")

        ninja.write(f"rule clean\n")
        ninja.write(f"  command = rm -rf bin obj iso_root gravitas.iso\n")
        ninja.write(f"  description = CLEAN\n\n")

        # --- TARGETS ---
        objects = []
        for src in cpp_sources:
            obj = "obj/" + src.replace("/", "_") + ".o"
            ninja.write(f"build {obj}: cxx {src}\n")
            objects.append(obj)

        for src in asm_sources:
            obj = "obj/" + src.replace("/", "_") + ".o"
            ninja.write(f"build {obj}: asm {src}\n")
            objects.append(obj)

        ninja.write(f"\nbuild {KERNEL_FILE}: link {' '.join(objects)}\n")

        user_elfs = []
        # All userland programs share one flat address space, so each program
        # gets its OWN load base. The shell owns 0x400000; everything else
        # lives at 32MB upwards, far above the per-task user stacks
        # (0x600000 + id * 1MB). Otherwise spawning one program zeroes
        # another program's bss and everything explodes.
        user_bases = {}
        next_base = 0x2000000
        for src in user_sources:
            stem = os.path.splitext(os.path.basename(src))[0]
            if stem == "shell":
                user_bases[stem] = 0x400000
            else:
                user_bases[stem] = next_base
                next_base += 0x100000
        for src in user_sources:
            stem = os.path.splitext(os.path.basename(src))[0]
            out = f"bin/{stem}.elf"
            # crt0 + all libc objects are real inputs so ninja builds them
            ninja.write(f"build {out}: userelf {src} {crt0_obj} {' '.join(libc_objects)}\n")
            ninja.write(f"  base = {user_bases[stem]:#x}\n")
            user_elfs.append(out)

        # The ISO needs the kernel AND every userland ELF (packed into the tar)
        ninja.write(f"build iso: iso {KERNEL_FILE} {' '.join(user_elfs)}\n")
        ninja.write(f"build run: run iso\n")
        ninja.write(f"build test: smoke iso\n")
        ninja.write(f"build clean: clean\n")

        ninja.write(f"\ndefault {KERNEL_FILE}\n")

    print("Configuration complete. Run 'ninja run' to boot, 'ninja test' to smoke-test.")

if __name__ == "__main__":
    main()
