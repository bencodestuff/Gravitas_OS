#pragma once
#include <stdint.h>

// Write 8 bits to a port
static inline void outb(uint16_t port, uint8_t val) {
    asm volatile ("outb %0, %1" : : "a"(val), "Nd"(port));
}

// Read 8 bits from a port
static inline uint8_t inb(uint16_t port) {
    uint8_t ret;
    asm volatile ("inb %1, %0" : "=a"(ret) : "Nd"(port));
    return ret;
}

// Write 16 bits to a port (ACPI's PM1a control register is 16-bit)
static inline void outw(uint16_t port, uint16_t val) {
    asm volatile ("outw %0, %1" : : "a"(val), "Nd"(port));
}

// Read 16 bits from a port (the PCI/virtio config registers are 16-bit)
static inline uint16_t inw(uint16_t port) {
    uint16_t ret;
    asm volatile ("inw %1, %0" : "=a"(ret) : "Nd"(port));
    return ret;
}

// 32 bits. PCI configuration space is addressed through a 32-bit port pair,
// so this is the width that layer speaks.
static inline uint32_t inl(uint16_t port) {
    uint32_t ret;
    asm volatile ("inl %1, %0" : "=a"(ret) : "Nd"(port));
    return ret;
}

static inline void outl(uint16_t port, uint32_t val) {
    asm volatile ("outl %0, %1" : : "a"(val), "Nd"(port));
}

// Wait a tiny bit (used for slow hardware like the PIC)
static inline void io_wait(void) {
    outb(0x80, 0);
}